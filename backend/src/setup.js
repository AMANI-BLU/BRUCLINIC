#!/usr/bin/env node
/**
 * BruClinic — First-Run Setup Wizard
 *
 * Run this script once after cloning to configure the system:
 *   node src/setup.js
 *
 * What it does:
 *   1. Check for existing .env file
 *   2. Collect database connection details interactively
 *   3. Test the database connection
 *   4. Generate a secure JWT secret
 *   5. Write a complete .env file
 *   6. Run database migrations
 *   7. Create the initial administrator account
 *
 * Non-interactive mode (for CI/CD or Docker):
 *   Set all SETUP_* environment variables and run with --non-interactive flag.
 *   Required: SETUP_DB_USER, SETUP_DB_PASSWORD, SETUP_DB_NAME,
 *             SETUP_ADMIN_USERNAME, SETUP_ADMIN_PASSWORD, SETUP_ADMIN_EMAIL
 *
 * The wizard never overwrites an existing .env unless --force is passed.
 */

import { createInterface } from 'node:readline';
import { randomBytes } from 'node:crypto';
import { readFile, writeFile, access } from 'node:fs/promises';
import { constants as fsConstants } from 'node:fs';
import { execSync, spawn } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const ENV_PATH = path.join(ROOT, '.env');
const ENV_EXAMPLE_PATH = path.join(ROOT, '.env.example');

// ── CLI Flags ─────────────────────────────────────────────────────
const args = process.argv.slice(2);
const NON_INTERACTIVE = args.includes('--non-interactive') || Boolean(process.env.BRUCLINIC_NON_INTERACTIVE);
const FORCE = args.includes('--force');
const SKIP_MIGRATIONS = args.includes('--skip-migrations');

// ── Colors ────────────────────────────────────────────────────────
const C = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  cyan: '\x1b[36m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  dim: '\x1b[2m',
};

function print(msg, color = '') { process.stdout.write(color + msg + C.reset + '\n'); }
function header(msg) { print(`\n  ╔══ ${msg} ══╗`, C.cyan + C.bold); }
function step(n, msg) { print(`\n  [${n}] ${msg}`, C.bold); }
function ok(msg) { print(`  ✓ ${msg}`, C.green); }
function warn(msg) { print(`  ⚠ ${msg}`, C.yellow); }
function fail(msg) { print(`  ✗ ${msg}`, C.red); }
function info(msg) { print(`    ${msg}`, C.dim); }

// ── Readline helper ───────────────────────────────────────────────
let rl;
function prompt(question, defaultValue = '', secret = false) {
  return new Promise(resolve => {
    const hint = defaultValue ? ` [${defaultValue}]` : '';
    rl.question(`  ${C.cyan}?${C.reset} ${question}${hint}: `, input => {
      resolve(input.trim() || defaultValue);
    });
  });
}

// ── Env file helpers ──────────────────────────────────────────────
async function envExists() {
  try { await access(ENV_PATH, fsConstants.F_OK); return true; } catch { return false; }
}

function buildEnvContent(config) {
  return `# BruClinic Environment Configuration
# Generated by setup wizard on ${new Date().toISOString()}
# Edit this file to change runtime settings. Restart the server after changes.

# ── Runtime ───────────────────────────────────────────────────────
NODE_ENV=${config.nodeEnv || 'production'}
HOST=${config.host || '0.0.0.0'}
PORT=${config.port || '4000'}
LOG_LEVEL=${config.logLevel || 'info'}

# ── Database ──────────────────────────────────────────────────────
DB_HOST=${config.dbHost || 'localhost'}
DB_PORT=${config.dbPort || '5432'}
DB_USER=${config.dbUser}
DB_PASSWORD=${config.dbPassword}
DB_NAME=${config.dbName || 'bruclinic'}
DATABASE_POOL_MAX=${config.poolMax || '10'}

# ── Security ──────────────────────────────────────────────────────
# NEVER share or commit this value. Rotate it if compromised.
JWT_SECRET=${config.jwtSecret}

# ── Network ───────────────────────────────────────────────────────
# Comma-separated list of allowed frontend origins (no trailing slash)
CORS_ORIGIN=${config.corsOrigin || 'http://localhost:5173'}
BODY_LIMIT_BYTES=${config.bodyLimit || '1048576'}

# ── Admin Account Seed (used by db:seed, cleared after use) ───────
SEED_ADMIN_USERNAME=${config.adminUsername}
SEED_ADMIN_PASSWORD=${config.adminPassword}
SEED_ADMIN_EMAIL=${config.adminEmail}
SEED_ADMIN_NAME=${config.adminName || 'Clinic Administrator'}
`;
}

// ── Database connection test ──────────────────────────────────────
async function testDatabaseConnection(config) {
  let client;
  try {
    const { Client } = await import('pg');
    client = new Client({
      host: config.dbHost || 'localhost',
      port: parseInt(config.dbPort || '5432', 10),
      user: config.dbUser,
      password: config.dbPassword,
      database: config.dbName,
      connectionTimeoutMillis: 5000,
    });
    await client.connect();
    await client.query('SELECT 1');
    return { success: true };
  } catch (err) {
    return { success: false, error: err.message, code: err.code };
  } finally {
    if (client) await client.end().catch(() => {});
  }
}

// ── Run npm script ────────────────────────────────────────────────
function runScript(script, envOverrides = {}) {
  return new Promise((resolve, reject) => {
    const env = { ...process.env, ...envOverrides };
    const child = spawn('node', ['src/' + script], { cwd: ROOT, env, stdio: 'inherit' });
    child.on('exit', code => code === 0 ? resolve() : reject(new Error(`Script ${script} exited with code ${code}`)));
  });
}

// ── Main Wizard ───────────────────────────────────────────────────
async function main() {
  print('\n');
  print('  ██████╗ ██████╗ ██╗   ██╗ ██████╗██╗     ██╗███╗   ██╗██╗ ██████╗', C.cyan);
  print('  ██╔══██╗██╔══██╗██║   ██║██╔════╝██║     ██║████╗  ██║██║██╔════╝', C.cyan);
  print('  ██████╔╝██████╔╝██║   ██║██║     ██║     ██║██╔██╗ ██║██║██║     ', C.cyan);
  print('  ██╔══██╗██╔══██╗██║   ██║██║     ██║     ██║██║╚██╗██║██║██║     ', C.cyan);
  print('  ██████╔╝██║  ██║╚██████╔╝╚██████╗███████╗██║██║ ╚████║██║╚██████╗', C.cyan);
  print('  ╚═════╝ ╚═╝  ╚═╝ ╚═════╝  ╚═════╝╚══════╝╚═╝╚═╝  ╚═══╝╚═╝ ╚═════╝', C.cyan);
  print('');
  print('  Borana University Clinic Management System — First-Run Setup', C.bold);
  print('  This wizard will configure your environment and database.\n', C.dim);

  if (!NON_INTERACTIVE) {
    rl = createInterface({ input: process.stdin, output: process.stdout });
  }

  // ── Step 1: Check for existing .env ──────────────────────────
  step(1, 'Checking for existing configuration');
  const exists = await envExists();
  if (exists && !FORCE) {
    warn('.env file already exists. Skipping setup to avoid overwriting.');
    info('Pass --force to overwrite the existing configuration.');
    info('Run "npm run db:migrate" and "npm run db:seed" manually if needed.');
    rl?.close();
    process.exit(0);
  }
  if (exists && FORCE) {
    warn('--force flag passed — existing .env will be overwritten!');
  }

  // ── Step 2: Database configuration ───────────────────────────
  step(2, 'Database connection');
  info('BruClinic requires PostgreSQL 14 or newer.');
  info('Create the database before running this wizard if it does not exist yet.');
  info('  Example: CREATE DATABASE bruclinic;\n');

  const config = {};

  if (NON_INTERACTIVE) {
    config.dbHost = process.env.SETUP_DB_HOST || 'localhost';
    config.dbPort = process.env.SETUP_DB_PORT || '5432';
    config.dbUser = process.env.SETUP_DB_USER;
    config.dbPassword = process.env.SETUP_DB_PASSWORD || '';
    config.dbName = process.env.SETUP_DB_NAME || 'bruclinic';
  } else {
    config.dbHost = await prompt('Database host', 'localhost');
    config.dbPort = await prompt('Database port', '5432');
    config.dbUser = await prompt('Database username', 'postgres');
    config.dbPassword = await prompt('Database password (leave blank if none)', '');
    config.dbName = await prompt('Database name', 'bruclinic');
  }

  if (!config.dbUser) { fail('Database username is required.'); rl?.close(); process.exit(1); }

  // ── Step 3: Test database connection ─────────────────────────
  step(3, 'Testing database connection');
  process.stdout.write('    Connecting...');
  const dbTest = await testDatabaseConnection(config);
  if (dbTest.success) {
    ok(' Connected successfully!');
  } else {
    print('');
    fail(`Cannot connect to database: ${dbTest.error}`);
    info(`Error code: ${dbTest.code || 'N/A'}`);
    info('');
    info('Troubleshooting tips:');
    info('  • Ensure PostgreSQL is running (systemctl start postgresql, or the Windows service)');
    info(`  • Create the database: CREATE DATABASE ${config.dbName};`);
    info('  • Check credentials and host/port settings');
    if (!NON_INTERACTIVE) {
      const cont = await prompt('Continue setup anyway? (yes/no)', 'no');
      if (cont.toLowerCase() !== 'yes') { rl?.close(); process.exit(1); }
      warn('Continuing without a confirmed DB connection. Migrations may fail.');
    } else {
      rl?.close(); process.exit(1);
    }
  }

  // ── Step 4: Security ──────────────────────────────────────────
  step(4, 'Security configuration');
  config.jwtSecret = randomBytes(48).toString('hex');
  ok(`Generated JWT secret (${config.jwtSecret.length} hex characters)`);

  if (NON_INTERACTIVE) {
    config.corsOrigin = process.env.SETUP_CORS_ORIGIN || 'http://localhost:5173';
    config.nodeEnv = process.env.SETUP_NODE_ENV || 'production';
    config.host = process.env.SETUP_HOST || '0.0.0.0';
    config.port = process.env.SETUP_PORT || '4000';
    config.logLevel = process.env.SETUP_LOG_LEVEL || 'info';
    config.poolMax = process.env.SETUP_POOL_MAX || '10';
    config.bodyLimit = process.env.SETUP_BODY_LIMIT || '1048576';
  } else {
    info('');
    config.corsOrigin = await prompt('Frontend URL (CORS origin)', 'http://localhost:5173');
    config.nodeEnv = await prompt('Environment (development/production)', 'production');
    config.host = await prompt('Server host (use 0.0.0.0 for all interfaces)', '0.0.0.0');
    config.port = await prompt('Server port', '4000');
  }

  // ── Step 5: Administrator account ────────────────────────────
  step(5, 'Administrator account');
  info('This creates the initial system administrator account.\n');

  if (NON_INTERACTIVE) {
    config.adminUsername = process.env.SETUP_ADMIN_USERNAME;
    config.adminPassword = process.env.SETUP_ADMIN_PASSWORD;
    config.adminEmail = process.env.SETUP_ADMIN_EMAIL;
    config.adminName = process.env.SETUP_ADMIN_NAME || 'Clinic Administrator';
  } else {
    config.adminName = await prompt('Admin full name', 'Clinic Administrator');
    config.adminUsername = await prompt('Admin username', 'admin');
    config.adminEmail = await prompt('Admin email', `admin@boru.edu.et`);
    let adminPass = '';
    let attempts = 0;
    while (attempts < 3) {
      adminPass = await prompt('Admin password (min 10 chars, uppercase + number required)');
      if (adminPass.length >= 10 && /[A-Z]/.test(adminPass) && /\d/.test(adminPass)) break;
      fail('Password does not meet requirements. Try again.');
      attempts++;
    }
    if (attempts === 3) { fail('Too many invalid attempts.'); rl?.close(); process.exit(1); }
    config.adminPassword = adminPass;
  }

  if (!config.adminUsername || !config.adminPassword || !config.adminEmail) {
    fail('Administrator credentials are required (username, password, email).'); rl?.close(); process.exit(1);
  }

  // ── Step 6: Write .env ────────────────────────────────────────
  step(6, 'Writing configuration file');
  await writeFile(ENV_PATH, buildEnvContent(config), 'utf8');
  ok(`.env written to: ${ENV_PATH}`);

  // ── Step 7: Run migrations ────────────────────────────────────
  if (!SKIP_MIGRATIONS) {
    step(7, 'Running database migrations');
    try {
      await runScript('db/migrate.js', {
        DB_HOST: config.dbHost, DB_PORT: config.dbPort,
        DB_USER: config.dbUser, DB_PASSWORD: config.dbPassword,
        DB_NAME: config.dbName, NODE_ENV: config.nodeEnv,
      });
      ok('Migrations completed');
    } catch (err) {
      fail(`Migration failed: ${err.message}`);
      info('Fix the issue and run: npm run db:migrate');
    }

    // ── Step 8: Seed admin account ──────────────────────────────
    step(8, 'Creating administrator account');
    try {
      await runScript('db/seed.js', {
        DB_HOST: config.dbHost, DB_PORT: config.dbPort,
        DB_USER: config.dbUser, DB_PASSWORD: config.dbPassword,
        DB_NAME: config.dbName, NODE_ENV: config.nodeEnv,
        SEED_ADMIN_USERNAME: config.adminUsername,
        SEED_ADMIN_PASSWORD: config.adminPassword,
        SEED_ADMIN_EMAIL: config.adminEmail,
        SEED_ADMIN_NAME: config.adminName,
        JWT_SECRET: config.jwtSecret,
      });
      ok(`Administrator account created: ${config.adminUsername}`);
    } catch (err) {
      fail(`Seed failed: ${err.message}`);
      info('Fix the issue and run: npm run db:seed');
    }
  } else {
    warn('Migrations skipped (--skip-migrations). Run "npm run db:migrate && npm run db:seed" manually.');
  }

  // ── Done ──────────────────────────────────────────────────────
  print('');
  print('  ════════════════════════════════════════════════════════════', C.green);
  print('  ✓  BruClinic setup complete!', C.green + C.bold);
  print('  ════════════════════════════════════════════════════════════', C.green);
  print('');
  print('  Next steps:', C.bold);
  info(`  1. Start the API server:     npm start  (or npm run dev for development)`);
  info(`  2. Start the frontend:       cd ../frontend && npm run dev`);
  info(`  3. Open in your browser:     ${config.corsOrigin}`);
  info(`  4. Sign in with username:    ${config.adminUsername}`);
  print('');
  warn('  Security reminder: Keep the .env file private and never commit it to version control.');
  print('');

  rl?.close();
}

main().catch(err => {
  fail(`Setup failed: ${err.message}`);
  process.exit(1);
});
